"""Lists what every combination of ingredients makes, from _data/kitchen.yml.

    python cooking/combos.py              writes cooking/combos.md (everything)
    python cooking/combos.py clementine   prints just clementine's combos

The matching is the same as assets/cooking/kitchen.js: recipes are tried top
to bottom, either order, first match wins. Each result is shown as designed
(as if every png existed), and when that dish isn't drawn yet, what the game
gives today instead.
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = yaml.safe_load((ROOT / '_data' / 'kitchen.yml').read_text(encoding='utf-8'))
DRAWN = {p.stem for p in (ROOT / 'assets' / 'cooking').glob('*.png')}

INGREDIENTS = DATA.get('ingredients') or []
DISHES = DATA.get('dishes') or []
RECIPES = DATA.get('recipes') or []
STATIONS = [s['id'] for s in DATA.get('stations') or []]
ITEMS = {i['id']: i for i in INGREDIENTS + DISHES}
NAMES = {i['id']: i.get('name', i['id']) for i in INGREDIENTS + DISHES}

# Which pages have a plant include, by kind.
PLACED = {}
for page in (ROOT / 'pages').rglob('*.md'):
    for kind in re.findall(r'plant\.html\s+kind="([^"]+)"', page.read_text(encoding='utf-8')):
        PLACED.setdefault(kind, []).append(page.relative_to(ROOT).as_posix())


def tags(item_id):
    return ITEMS[item_id].get('tags') or []


def matches(token, item_id):
    if token == 'anything':
        return True
    if token == 'nothing':
        return item_id is None
    if item_id is None:
        return False
    if token.startswith('any '):
        return token[4:] in tags(item_id)
    return token == item_id


def recipe(station, a, b, drawn_only):
    """(result, recipe) for the first recipe that fits, or (None, None)."""
    for r in RECIPES:
        if r['at'] != station:
            continue
        if drawn_only and r['out'] not in DRAWN:
            continue
        ins = r['in']
        p, q = ins[0], ins[1] if len(ins) > 1 else 'nothing'
        if (matches(p, a) and matches(q, b)) or (matches(p, b) and matches(q, a)):
            return r['out'], r
    return None, None


def kind_of(r):
    """How specific the matching recipe was."""
    if r is None:
        return 'nothing matches'
    tokens = r['in'] if len(r['in']) > 1 else r['in'] + ['nothing']
    if 'anything' in tokens:
        return 'catch-all'
    if any(t.startswith('any ') for t in tokens):
        return 'tag rule'
    return 'exact'


def cookable(item_id):
    """Ingredients always; dishes only if they have tags."""
    item = ITEMS[item_id]
    return item in INGREDIENTS or bool(item.get('tags'))


def partners():
    return [None] + [i for i in ITEMS if cookable(i)]


def combo_rows(station, item_id):
    rows = []
    for other in partners():
        out, r = recipe(station, item_id, other, drawn_only=False)
        today, _ = recipe(station, item_id, other, drawn_only=True)
        rows.append((other, out, kind_of(r), today))
    return rows


def label(item_id):
    return '(nothing)' if item_id is None else NAMES[item_id]


def fmt_result(out, today):
    if out is None:
        return 'nothing (the pot refuses)'
    text = NAMES[out]
    if out not in DRAWN:
        text += f' (not drawn; today: {NAMES[today] if today else "refused"})'
    return text


def combo_table(station, item_id):
    lines = ['| with | makes | rule |', '|---|---|---|']
    for other, out, kind, today in combo_rows(station, item_id):
        lines.append(f'| {label(other)} | {fmt_result(out, today)} | {kind} |')
    return lines


def tick(ok):
    return 'yes' if ok else '-'


def report():
    out = [
        '# cooking combos',
        '',
        'Generated by `python cooking/combos.py` from `_data/kitchen.yml`. Do not edit;',
        'rerun it after changing the yml or adding pngs.',
        '',
        '## ingredients',
        '',
        '| id | name | tags | sprite | plant sprite | placed on |',
        '|---|---|---|---|---|---|',
    ]
    plants = {p.get('item', p['id']): p for p in DATA.get('plants') or []}
    for i in INGREDIENTS:
        p = plants.get(i['id'])
        pid = p['id'] if p else None
        if not p:
            plant = 'no plant entry'
        elif p.get('bare'):
            plant = 'none (lies on the ground)'
        else:
            plant = tick((p.get('look') or pid) + 'plant' in DRAWN)
        placed = ', '.join(PLACED.get(pid, [])) if pid else ''
        out.append(f"| {i['id']} | {i.get('name', '')} | {', '.join(tags(i['id']))} "
                   f"| {tick(i['id'] in DRAWN)} | {plant} | {placed or '-'} |")

    out += ['', '## dishes', '', '| id | name | sprite | made by |', '|---|---|---|---|']
    for d in DISHES:
        makers = [f"{r['at']}: {' + '.join(r['in'])}" for r in RECIPES if r['out'] == d['id']]
        out.append(f"| {d['id']} | {d.get('name', '')} | {tick(d['id'] in DRAWN)} "
                   f"| {'; '.join(makers) or 'no recipe'} |")

    for station in STATIONS:
        if not any(r['at'] == station for r in RECIPES):
            continue
        out += ['', f'## {station}', '']
        for i in ITEMS:
            if not cookable(i):
                continue
            out += [f'### {label(i)}', ''] + combo_table(station, i) + ['']
    return '\n'.join(out) + '\n'


def main():
    if len(sys.argv) > 1:
        item_id = sys.argv[1]
        if item_id not in ITEMS:
            sys.exit(f'no item "{item_id}" in _data/kitchen.yml')
        for station in STATIONS:
            if any(r['at'] == station for r in RECIPES):
                print(f'## {station}\n')
                print('\n'.join(combo_table(station, item_id)) + '\n')
        return
    path = ROOT / 'cooking' / 'combos.md'
    path.write_text(report(), encoding='utf-8')
    print(f'wrote {path}')


if __name__ == '__main__':
    main()
